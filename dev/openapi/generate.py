"""Generates MSS's models of the events a backend sends over its websocket, from its spec

Run from the repository root: `python -m dev.openapi.generate`. The spec, bcc.json, is a copy
of tergite-backend's committed OpenAPI schema (dev/openapi/sync.sh copies it), pruned to the
events and MSS's reply to each, and the schemas they refer to, so that a change elsewhere in
the backend does not touch MSS. tests/test_openapi.py fails when the models no longer match it.
"""

import json
import subprocess
import tempfile
from pathlib import Path
from typing import Any, Dict, Iterable, Set

from datamodel_code_generator import DataModelType, InputFileType, generate
from ruff.__main__ import find_ruff_bin

OPENAPI_DIR = Path(__file__).parent
ROOT_DIR = OPENAPI_DIR.parents[1]
SPEC_FILE = OPENAPI_DIR / "bcc.json"
MODELS_FILE = ROOT_DIR / "services" / "external" / "bcc" / "events.py"
# the events' envelope, and MSS's reply to each
SCHEMAS = ("DeviceEvent", "EventResponse")
HEADER = """# This code is part of Tergite
#
# (C) Copyright Chalmers Next Labs AB 2026
#
# This code is licensed under the Apache License, Version 2.0. You may
# obtain a copy of this license in the LICENSE.txt file in the root directory
# of this source tree or at http://www.apache.org/licenses/LICENSE-2.0.
#
# Any modifications or derivative works of this code must retain this
# copyright notice, and modified files need to carry a notice indicating
# that they have been altered from the originals.
#
# Generated by dev/openapi/generate.py from dev/openapi/bcc.json; do not edit."""


def main() -> None:
    MODELS_FILE.write_text(render_models())


def render_models() -> str:
    """Renders the Python source of the events' models, from the backend's spec

    Returns:
        the source of the models module
    """
    spec = json.loads(SPEC_FILE.read_text())
    pruned = prune_spec(spec, SCHEMAS)
    with tempfile.TemporaryDirectory() as folder:
        output = Path(folder) / "events.py"
        generate(
            json.dumps(pruned),
            input_file_type=InputFileType.OpenAPI,
            output=output,
            output_model_type=DataModelType.PydanticV2BaseModel,
            custom_file_header=HEADER,
            use_standard_collections=True,
            use_union_operator=True,
            use_schema_description=True,
            use_double_quotes=True,
            collapse_root_models=True,
            use_tuple_for_fixed_items=True,
            disable_timestamp=True,
            # formatted below, as this repository's ruff settings would format it
            formatters=[],
        )
        source = output.read_text()
    return _format(source, MODELS_FILE)


def prune_spec(spec: Dict[str, Any], schemas: Iterable[str]) -> Dict[str, Any]:
    """The spec without paths, and with only the schemas and those they refer to

    Args:
        spec: the backend's OpenAPI spec
        schemas: the names of the schemas to keep

    Returns:
        the pruned spec
    """
    all_schemas = spec["components"]["schemas"]
    kept = _get_referred_schemas(all_schemas, set(schemas))
    return {
        "openapi": spec["openapi"],
        "info": spec["info"],
        "paths": {},
        "components": {
            "schemas": {name: make_lenient(all_schemas[name]) for name in sorted(kept)}
        },
    }


def make_lenient(node: Any) -> Any:
    """The schema node, and every node in it, as lenient as MSS reading it should be:

    - a read-only field is optional: the backend dumps a job with exclude_none, so a null
      one, such as its duration_in_secs, is left out though the schema requires it;
    - a string has no pattern: the backend validates its own ids, and MSS keeps them as given;
    - an object takes fields it does not declare: a newer backend may send more, which MSS
      drops, where refusing them would refuse the whole event.

    Args:
        node: a node of the spec

    Returns:
        the node, made lenient
    """
    if isinstance(node, list):
        return [make_lenient(item) for item in node]
    if not isinstance(node, dict):
        return node

    schema = {
        key: make_lenient(value)
        for key, value in node.items()
        if key != "pattern" and not (key == "additionalProperties" and value is False)
    }
    if "required" in schema and isinstance(schema.get("properties"), dict):
        properties = schema["properties"]
        schema["required"] = [
            name
            for name in schema["required"]
            if not properties.get(name, {}).get("readOnly")
        ]
    return schema


def _get_referred_schemas(all_schemas: Dict[str, Any], names: Set[str]) -> Set[str]:
    """The schemas named, and every schema they refer to, however deep"""
    kept: Set[str] = set()
    pending = list(names)
    while pending:
        name = pending.pop()
        if name in kept:
            continue
        kept.add(name)
        pending.extend(_get_refs(all_schemas[name]))
    return kept


def _get_refs(node: Any) -> Iterable[str]:
    """The names of the schemas the node refers to"""
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            yield ref.rsplit("/", 1)[-1]
        for value in node.values():
            yield from _get_refs(value)
    elif isinstance(node, list):
        for item in node:
            yield from _get_refs(item)


def _format(source: str, path: Path) -> str:
    """Sorts the imports of the source and formats it, as ruff would the file at path"""
    sorted_source = _run_ruff(
        ["check", "--fix-only", "--select", "I"], source=source, path=path
    )
    return _run_ruff(["format"], source=sorted_source, path=path)


def _run_ruff(arguments: list[str], source: str, path: Path) -> str:
    """Runs ruff on the source as the file at path, under this repository's config"""
    return subprocess.run(
        [find_ruff_bin(), *arguments, "--stdin-filename", str(path), "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT_DIR,
    ).stdout


if __name__ == "__main__":
    main()
